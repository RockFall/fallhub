def render_icon(name: str, scale=3) -> Image.Image:
    rows = ico(ICONS[name])
    sp = Sprite(16, 16)
    sp.stamp(0, 0, rows, P)
    return sp.image(scale)


def make_mono(im: Image.Image, color=W) -> Image.Image:
    out = Image.new("RGBA", im.size, (0, 0, 0, 0))
    src = im.load()
    dst = out.load()
    for y in range(im.height):
        for x in range(im.width):
            a = src[x, y][3]
            if a > 20:
                dst[x, y] = (color[0], color[1], color[2], a)
    return out


def process_portrait() -> Image.Image:
    src_path = next((p for p in (PORTRAIT_SRC, PORTRAIT_REPO) if p.exists()), None)
    canvas = Image.new("RGBA", (64, 64), (18, 20, 24, 255))
    if src_path is None:
        sp = Sprite(32, 32)
        sp.stamp(8, 4, ico(ICONS["person"]), P)
        return sp.image(2)

    src = Image.open(src_path).convert("RGBA")
    # drop near-black so the inset well shows through at the corners
    px = src.load()
    for y in range(src.height):
        for x in range(src.width):
            r, g, b, a = px[x, y]
            if r < 18 and g < 18 and b < 18:
                px[x, y] = (0, 0, 0, 0)
    bbox = src.getbbox()
    if bbox:
        src = src.crop(bbox)
    # chunky pixels: box-down then nearest up
    small = src.resize((40, 48), Image.Resampling.BOX)
    pal = small.convert("P", palette=Image.Palette.ADAPTIVE, colors=16)
    small = pal.convert("RGBA")
    pixel = small.resize((48, 56), Image.Resampling.NEAREST)
    canvas.paste(pixel, (8, 4), pixel)
    return canvas


def make_hull_plates() -> Image.Image:
    src = METAL_SRC if METAL_SRC.exists() else METAL_REPO
    if src.exists():
        im = Image.open(src).convert("RGBA")
        im = im.resize((64, 64), Image.Resampling.BOX)
        return ImageEnhance.Brightness(im).enhance(0.55)
    return make_grain(64)


def make_catalog(icons: dict[str, Image.Image]) -> Image.Image:
    names = sorted(icons)
    cols = 8
    rows = math.ceil(len(names) / cols)
    cell = 72
    im = Image.new("RGBA", (cols * cell, rows * cell + 24), (*VOID[:3], 255))
    d = ImageDraw.Draw(im)
    for i, name in enumerate(names):
        x = (i % cols) * cell
        y = (i // cols) * cell
        icon = icons[name].resize((48, 48), Image.Resampling.NEAREST)
        im.paste(icon, (x + 12, y + 4), icon)
        d.text((x + 4, y + 54), name[:10], fill=W)
    return im


