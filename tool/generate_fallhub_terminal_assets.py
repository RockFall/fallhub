def ico(rows: str) -> list[str]:
    lines = [ln for ln in rows.strip("\n").split("\n")]
    # pad/trim to 16
    out = []
    for ln in lines[:16]:
        ln = ln[:16].ljust(16, ".")
        out.append(ln)
    while len(out) < 16:
        out.append("." * 16)
    return out


