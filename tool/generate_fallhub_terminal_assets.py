def _rgba(c, a=255):
    if len(c) == 4:
        return c
    return (c[0], c[1], c[2], a)


class Sprite:
    def __init__(self, w: int, h: int):
        self.w = w
        self.h = h
        self.px = [[None] * w for _ in range(h)]

    def put(self, x, y, c):
        if 0 <= x < self.w and 0 <= y < self.h and c is not None:
            self.px[y][x] = _rgba(c)

    def fill(self, x, y, w, h, c):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                self.put(xx, yy, c)

    def rect(self, x, y, w, h, c):
        for xx in range(x, x + w):
            self.put(xx, y, c)
            self.put(xx, y + h - 1, c)
        for yy in range(y, y + h):
            self.put(x, yy, c)
            self.put(x + w - 1, yy, c)

    def line(self, x0, y0, x1, y1, c):
        dx, dy = abs(x1 - x0), abs(y1 - y0)
        sx = 1 if x0 < x1 else -1
        sy = 1 if y0 < y1 else -1
        err = dx - dy
        while True:
            self.put(x0, y0, c)
            if x0 == x1 and y0 == y1:
                break
            e2 = 2 * err
            if e2 > -dy:
                err -= dy
                x0 += sx
            if e2 < dx:
                err += dx
                y0 += sy

    def circle(self, cx, cy, r, c, fill=True):
        for y in range(cy - r, cy + r + 1):
            for x in range(cx - r, cx + r + 1):
                d2 = (x - cx) ** 2 + (y - cy) ** 2
                if fill:
                    if d2 <= r * r + r * 0.2:
                        self.put(x, y, c)
                else:
                    if abs(math.sqrt(d2) - r) < 0.7:
                        self.put(x, y, c)

    def stamp(self, x, y, rows, pal):
        for j, row in enumerate(rows):
            for i, ch in enumerate(row):
                if ch in pal and pal[ch] is not None:
                    self.put(x + i, y + j, pal[ch])

    def image(self, scale=1) -> Image.Image:
        im = Image.new("RGBA", (self.w, self.h), (0, 0, 0, 0))
        p = im.load()
        for y in range(self.h):
            for x in range(self.w):
                if self.px[y][x]:
                    p[x, y] = self.px[y][x]
        if scale > 1:
            im = im.resize((self.w * scale, self.h * scale), Image.Resampling.NEAREST)
        return im

    def save(self, path: Path, scale=2):
        path.parent.mkdir(parents=True, exist_ok=True)
        self.image(scale).save(path, "PNG")


def save_scaled(im: Image.Image, path: Path, scale=1):
    path.parent.mkdir(parents=True, exist_ok=True)
    if scale != 1:
        im = im.resize((im.width * scale, im.height * scale), Image.Resampling.NEAREST)
    im.save(path, "PNG")


def rivet(draw: ImageDraw.ImageDraw, x, y, r=2):
    draw.ellipse((x - r, y - r, x + r, y + r), fill=MD)
    draw.ellipse((x - r + 1, y - r + 1, x + r - 1, y + r - 1), fill=M)
    draw.point((x - 1, y - 1), fill=MH)


def make_panel_9(size=36, fill=PANEL, inset=False) -> Image.Image:
    im = Image.new("RGBA", (size, size), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    r = 5
    box = [0, 0, size - 1, size - 1]
    d.rounded_rectangle(box, radius=r, fill=K)
    inner = [1, 1, size - 2, size - 2]
    face = (20, 22, 26, 255) if inset else fill
    d.rounded_rectangle(inner, radius=r - 1, fill=face)
    # bevel
    hi = (70, 74, 80, 255) if not inset else (40, 44, 48, 255)
    sh = (8, 9, 11, 255)
    for i in range(2, size - 2):
        im.putpixel((i, 2), hi)
        im.putpixel((i, size - 3), sh)
        im.putpixel((2, i), hi)
        im.putpixel((size - 3, i), sh)
    rivet(d, 6, 6, 2)
    rivet(d, size - 7, 6, 2)
    rivet(d, 6, size - 7, 2)
    rivet(d, size - 7, size - 7, 2)
    return im


def make_button_9(size=(48, 24), pressed=False) -> Image.Image:
    w, h = size
    im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
